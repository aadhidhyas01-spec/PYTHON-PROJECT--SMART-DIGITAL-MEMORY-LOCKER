-- Smart Digital Memory Locker - Supabase setup
-- The Flask app uses SUPABASE_SECRET_KEY server-side only.
-- Never put this secret in browser JavaScript or commit it to Git.

CREATE TABLE IF NOT EXISTS records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    value REAL NOT NULL,
    date TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name TEXT NOT NULL,
    stored_name TEXT NOT NULL,
    file_type TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    category TEXT DEFAULT 'General',
    uploaded_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Do not allow direct public access. The trusted Flask backend connects
-- using SUPABASE_SECRET_KEY and performs the application checks.
ALTER TABLE records ENABLE ROW LEVEL SECURITY;
ALTER TABLE files ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE records, files FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
GRANT ALL ON TABLE records, files TO service_role;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO service_role;
